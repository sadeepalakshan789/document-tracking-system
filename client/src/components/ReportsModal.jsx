import React, { useEffect, useMemo, useState } from "react";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { getSystemReportData } from "../services/api";
import { PriorityBadge, DueDateBadge } from "./PriorityBadge";

const getTodayString = () => {
  const d = new Date();
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
};

const formatDate = (dateStr) => {
  if (!dateStr) return "—";
  try {
    const d = new Date(dateStr);
    return d.toLocaleString("en-US", {
      year: "numeric",
      month: "short",
      day: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    });
  } catch {
    return dateStr;
  }
};

const formatShortDate = (dateStr) => {
  if (!dateStr) return "";
  try {
    const d = new Date(dateStr);
    return d.toISOString().split("T")[0];
  } catch {
    return "";
  }
};

export default function ReportsModal({ isOpen, onClose, currentUser }) {
  const [period, setPeriod] = useState("daily"); // "daily" | "weekly" | "monthly"
  const [selectedDate, setSelectedDate] = useState(getTodayString());
  const [reportData, setReportData] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [copiedId, setCopiedId] = useState(null);
  const [searchDoc, setSearchDoc] = useState("");
  const [statusFilter, setStatusFilter] = useState("ALL");
  const [pdfGenerating, setPdfGenerating] = useState(false);
  const [csvGenerating, setCsvGenerating] = useState(false);

  // Esc key listener
  useEffect(() => {
    if (!isOpen) return;
    const handleKeyDown = (e) => {
      if (e.key === "Escape") {
        onClose();
      }
    };
    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [isOpen, onClose]);

  // Fetch report data on period or date change
  const fetchReport = async () => {
    setLoading(true);
    setError("");
    try {
      const res = await getSystemReportData({
        period,
        date: selectedDate,
      });
      setReportData(res.data);
    } catch (err) {
      console.error("Failed to load report data:", err);
      setError(
        err.response?.data?.message || "Failed to load report data. Please try again."
      );
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (isOpen) {
      fetchReport();
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [isOpen, period, selectedDate]);

  // Copy tracking ID
  const handleCopyId = (id) => {
    navigator.clipboard.writeText(id);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  // Filtered documents list for preview table
  const filteredDocuments = useMemo(() => {
    if (!reportData?.documents) return [];
    return reportData.documents.filter((doc) => {
      const q = searchDoc.toLowerCase().trim();
      const matchSearch =
        !q ||
        doc.trackingId?.toLowerCase().includes(q) ||
        doc.title?.toLowerCase().includes(q) ||
        doc.createdBy?.toLowerCase().includes(q) ||
        doc.currentHolder?.toLowerCase().includes(q);

      const matchStatus =
        statusFilter === "ALL" ||
        doc.status?.toUpperCase() === statusFilter.toUpperCase();

      return matchSearch && matchStatus;
    });
  }, [reportData, searchDoc, statusFilter]);

  // ─────────────────────────────────────────────────────────────────────────
  //  PDF Generator
  // ─────────────────────────────────────────────────────────────────────────
  const handleDownloadPDF = () => {
    if (!reportData) return;
    setPdfGenerating(true);

    try {
      const doc = new jsPDF({
        orientation: "portrait",
        unit: "mm",
        format: "a4",
      });

      const primaryColor = [79, 70, 229]; // indigo-600
      const darkColor = [15, 23, 42]; // slate-900
      const mutedColor = [100, 116, 139]; // slate-500

      // Title & Branding
      doc.setFont("helvetica", "bold");
      doc.setFontSize(18);
      doc.setTextColor(primaryColor[0], primaryColor[1], primaryColor[2]);
      doc.text("DOCUMENT WORKFLOW ADMIN REPORT", 14, 20);

      doc.setFont("helvetica", "normal");
      doc.setFontSize(10);
      doc.setTextColor(mutedColor[0], mutedColor[1], mutedColor[2]);
      doc.text("Generated by CodeBloom Document Tracking System", 14, 26);

      // Metadata box
      const dateRangeStr =
        period === "daily"
          ? `Date: ${selectedDate}`
          : period === "weekly"
          ? `Last 7 Days (Ending: ${selectedDate})`
          : `Month: ${selectedDate.substring(0, 7)}`;

      doc.setDrawColor(226, 232, 240);
      doc.setFillColor(248, 250, 252);
      doc.roundedRect(14, 30, 182, 22, 2, 2, "FD");

      doc.setFontSize(9);
      doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
      doc.setFont("helvetica", "bold");
      doc.text("Report Scope:", 18, 37);
      doc.setFont("helvetica", "normal");
      doc.text(`${period.toUpperCase()} (${dateRangeStr})`, 48, 37);

      doc.setFont("helvetica", "bold");
      doc.text("Generated By:", 18, 45);
      doc.setFont("helvetica", "normal");
      doc.text(currentUser?.name || "Super Admin", 48, 45);

      doc.setFont("helvetica", "bold");
      doc.text("Generated On:", 115, 45);
      doc.setFont("helvetica", "normal");
      doc.text(new Date().toLocaleString(), 142, 45);

      // Summary Table
      const summary = reportData.workflowSummary || {};
      const userSummary = reportData.userActivity || {};

      const summaryRows = [
        [
          "Total Documents",
          String(summary.total ?? 0),
          "Active Accounts",
          String(userSummary.totalActive ?? 0),
        ],
        [
          "In Transit",
          String(summary.inTransit ?? 0),
          "Blocked Accounts",
          String(userSummary.totalBlocked ?? 0),
        ],
        [
          "Pending Acceptance",
          String(summary.pendingAcceptance ?? 0),
          "New Users in Period",
          String(userSummary.newUsersPeriod ?? 0),
        ],
        [
          "Completed",
          String(summary.completed ?? 0),
          "Overdue / Delayed (>48h)",
          String(summary.delayed ?? 0),
        ],
      ];

      autoTable(doc, {
        startY: 56,
        head: [["Workflow Metric", "Count", "Account Activity", "Count"]],
        body: summaryRows,
        theme: "grid",
        headStyles: {
          fillColor: [79, 70, 229],
          textColor: 255,
          fontStyle: "bold",
          fontSize: 9,
        },
        styles: {
          fontSize: 8.5,
          cellPadding: 2.5,
          textColor: [30, 41, 59],
        },
        columnStyles: {
          0: { fontStyle: "bold", cellWidth: 55 },
          1: { halign: "center", fontStyle: "bold", cellWidth: 35 },
          2: { fontStyle: "bold", cellWidth: 55 },
          3: { halign: "center", fontStyle: "bold", cellWidth: 37 },
        },
      });

      // Top Handlers note if available
      let nextStartY = (doc).lastAutoTable.finalY + 8;
      if (userSummary.topHandlers && userSummary.topHandlers.length > 0) {
        doc.setFont("helvetica", "bold");
        doc.setFontSize(10);
        doc.setTextColor(darkColor[0], darkColor[1], darkColor[2]);
        doc.text("Top Active Handlers:", 14, nextStartY);

        const handlerStr = userSummary.topHandlers
          .map((h) => `${h.name} (${h.count} docs)`)
          .join("   •   ");
        doc.setFont("helvetica", "normal");
        doc.setFontSize(8.5);
        doc.setTextColor(mutedColor[0], mutedColor[1], mutedColor[2]);
        doc.text(handlerStr, 14, nextStartY + 5);
        nextStartY += 12;
      }

      // Detailed Documents Table
      const docs = reportData.documents || [];
      const docRows = docs.map((d) => [
        d.trackingId || "—",
        d.title || "Untitled",
        (d.priority || "Normal").toUpperCase(),
        d.currentHolder || "None",
        d.status || "—",
        d.dueDate ? `${formatShortDate(d.dueDate)}${d.isOverdue ? " [OVERDUE]" : ""}` : "None",
        formatShortDate(d.updatedAt || d.createdAt),
      ]);

      autoTable(doc, {
        startY: nextStartY,
        head: [
          [
            "Tracking ID",
            "Document Title",
            "Priority",
            "Current Holder",
            "Status",
            "Due Date",
            "Updated",
          ],
        ],
        body: docRows.length > 0 ? docRows : [["No documents found for this period", "", "", "", "", "", ""]],
        theme: "striped",
        headStyles: {
          fillColor: [30, 41, 59],
          textColor: 255,
          fontStyle: "bold",
          fontSize: 8.5,
        },
        styles: {
          fontSize: 7.5,
          cellPadding: 2.2,
          overflow: "linebreak",
        },
        columnStyles: {
          0: { fontStyle: "bold", cellWidth: 26 },
          1: { cellWidth: 38 },
          2: { fontStyle: "bold", cellWidth: 22 },
          3: { cellWidth: 26 },
          4: { fontStyle: "bold", cellWidth: 22 },
          5: { cellWidth: 26 },
          6: { cellWidth: 22 },
        },
        didDrawPage: (data) => {
          // Page number footer
          const pageStr = `Page ${doc.internal.getNumberOfPages()}`;
          doc.setFontSize(8);
          doc.setTextColor(150);
          doc.text(pageStr, 196, 290, { align: "right" });
          doc.text("CodeBloom Document Workflow System", 14, 290);
        },
      });

      // Save PDF
      const filename = `CodeBloom_Workflow_Report_${period}_${selectedDate}.pdf`;
      doc.save(filename);
    } catch (err) {
      console.error("PDF generation error:", err);
      alert("Failed to generate PDF. Please try again.");
    } finally {
      setPdfGenerating(false);
    }
  };

  // ─────────────────────────────────────────────────────────────────────────
  //  CSV Generator
  // ─────────────────────────────────────────────────────────────────────────
  const handleDownloadCSV = () => {
    if (!reportData) return;
    setCsvGenerating(true);

    try {
      const summary = reportData.workflowSummary || {};
      const userSummary = reportData.userActivity || {};
      const docs = reportData.documents || [];

      const escapeCsv = (str) => {
        if (str === null || str === undefined) return '""';
        const s = String(str).replace(/"/g, '""');
        return `"${s}"`;
      };

      const rows = [];
      // Title
      rows.push(["CodeBloom Document Tracking System - Workflow Report"]);
      rows.push([`Period: ${period.toUpperCase()}`, `Date/Anchor: ${selectedDate}`]);
      rows.push([`Generated By: ${currentUser?.name || "Super Admin"}`, `Generated At: ${new Date().toISOString()}`]);
      rows.push([]);

      // Summary
      rows.push(["--- WORKFLOW & SYSTEM SUMMARY ---"]);
      rows.push(["Metric", "Count"]);
      rows.push(["Total Documents", summary.total ?? 0]);
      rows.push(["In Transit", summary.inTransit ?? 0]);
      rows.push(["Pending Acceptance", summary.pendingAcceptance ?? 0]);
      rows.push(["Completed", summary.completed ?? 0]);
      rows.push(["Overdue / Delayed (>48h)", summary.delayed ?? 0]);
      rows.push(["Total Active Accounts", userSummary.totalActive ?? 0]);
      rows.push(["Total Blocked Accounts", userSummary.totalBlocked ?? 0]);
      rows.push(["New Users in Period", userSummary.newUsersPeriod ?? 0]);
      rows.push([]);

      // Top Handlers
      if (userSummary.topHandlers?.length > 0) {
        rows.push(["--- TOP ACTIVE HANDLERS ---"]);
        rows.push(["Handler Name", "Document Touch Count"]);
        userSummary.topHandlers.forEach((h) => {
          rows.push([h.name, h.count]);
        });
        rows.push([]);
      }

      // Document Log
      rows.push(["--- DETAILED DOCUMENT LOG ---"]);
      rows.push([
        "Tracking ID",
        "Document Title",
        "Priority",
        "Sender / Creator",
        "Current Holder",
        "Status",
        "Due Date / SLA",
        "Is Overdue",
        "Created At",
        "Last Updated",
      ]);

      docs.forEach((d) => {
        rows.push([
          d.trackingId || "",
          d.title || "",
          d.priority || "Normal",
          d.createdBy || "",
          d.currentHolder || "",
          d.status || "",
          d.dueDate ? new Date(d.dueDate).toISOString() : "",
          d.isOverdue ? "YES" : "NO",
          d.createdAt ? new Date(d.createdAt).toISOString() : "",
          d.updatedAt ? new Date(d.updatedAt).toISOString() : "",
        ]);
      });

      const csvContent = rows.map((r) => r.map(escapeCsv).join(",")).join("\r\n");
      const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.setAttribute(
        "download",
        `CodeBloom_Workflow_Report_${period}_${selectedDate}.csv`
      );
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      URL.revokeObjectURL(url);
    } catch (err) {
      console.error("CSV generation error:", err);
      alert("Failed to export CSV. Please try again.");
    } finally {
      setCsvGenerating(false);
    }
  };

  if (!isOpen) return null;

  const summary = reportData?.workflowSummary || {
    total: 0,
    inTransit: 0,
    pendingAcceptance: 0,
    completed: 0,
    delayed: 0,
  };

  const userSummary = reportData?.userActivity || {
    totalActive: 0,
    totalBlocked: 0,
    newUsersPeriod: 0,
    topHandlers: [],
  };

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-black/75 backdrop-blur-sm p-3 sm:p-5 animate-fade-in"
      onClick={onClose}
    >
      <div
        className="relative bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 text-slate-900 dark:text-slate-100 w-full max-w-5xl h-[90vh] max-h-[820px] rounded-3xl p-5 sm:p-7 shadow-2xl flex flex-col overflow-hidden transition-all duration-300"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Modal Header */}
        <div className="flex items-start justify-between pb-4 border-b border-slate-200 dark:border-slate-800 flex-shrink-0">
          <div className="flex items-center gap-3">
            <div className="p-2.5 bg-amber-100 dark:bg-amber-900/40 border border-amber-300/40 dark:border-amber-600/30 rounded-2xl text-amber-600 dark:text-amber-400">
              <svg
                className="w-6 h-6"
                fill="none"
                viewBox="0 0 24 24"
                stroke="currentColor"
                strokeWidth={2}
              >
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M19.5 14.25v-2.625a3.375 3.375 0 00-3.375-3.375h-1.5A1.125 1.125 0 0113.5 7.125v-1.5a3.375 3.375 0 00-3.375-3.375H8.25m0 12.75h7.5m-7.5 3H12M10.5 2.25H5.625c-.621 0-1.125.504-1.125 1.125v17.25c0 .621.504 1.125 1.125 1.125h12.75c.621 0 1.125-.504 1.125-1.125V11.25a9 9 0 00-9-9z"
                />
              </svg>
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-xl font-bold text-slate-900 dark:text-slate-100">
                  Generate Reports
                </h2>
                <span className="inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-bold bg-amber-500/10 text-amber-600 dark:text-amber-400 border border-amber-500/20">
                  Analytics &amp; Audit
                </span>
              </div>
              <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5">
                Download Daily, Weekly &amp; Monthly workflow summaries and detailed document logs.
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="text-slate-400 hover:text-slate-600 dark:hover:text-slate-200 transition-colors p-2 rounded-xl hover:bg-slate-100 dark:hover:bg-slate-800 cursor-pointer"
            title="Close (Esc)"
          >
            <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>

        {/* Filter & Period Control Toolbar */}
        <div className="pt-4 pb-3 flex flex-wrap items-center justify-between gap-3 flex-shrink-0">
          <div className="flex flex-wrap items-center gap-2">
            {/* Period Tabs */}
            <div className="inline-flex rounded-xl bg-slate-100 dark:bg-slate-800 p-1 border border-slate-200 dark:border-slate-700/60">
              {[
                { id: "daily", label: "Daily" },
                { id: "weekly", label: "Weekly" },
                { id: "monthly", label: "Monthly" },
              ].map((t) => (
                <button
                  key={t.id}
                  type="button"
                  onClick={() => setPeriod(t.id)}
                  className={`px-3.5 py-1.5 rounded-lg text-xs font-bold transition-all cursor-pointer ${
                    period === t.id
                      ? "bg-white dark:bg-slate-900 text-indigo-600 dark:text-indigo-400 shadow-sm"
                      : "text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-slate-200"
                  }`}
                >
                  {t.label}
                </button>
              ))}
            </div>

            {/* Date Picker */}
            <div className="flex items-center gap-1.5 bg-slate-50 dark:bg-slate-800/70 border border-slate-200 dark:border-slate-700 rounded-xl px-2.5 py-1.5">
              <span className="text-[11px] font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
                Date:
              </span>
              <input
                type="date"
                value={selectedDate}
                onChange={(e) => setSelectedDate(e.target.value)}
                className="bg-transparent text-xs text-slate-900 dark:text-slate-100 focus:outline-none cursor-pointer"
              />
            </div>

            {/* Refresh */}
            <button
              onClick={fetchReport}
              disabled={loading}
              className="p-2 rounded-xl bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 border border-slate-200 dark:border-slate-700 text-slate-600 dark:text-slate-300 transition cursor-pointer"
              title="Refresh Data"
            >
              <svg
                className={`w-4 h-4 ${loading ? "animate-spin text-indigo-500" : ""}`}
                fill="none"
                viewBox="0 0 24 24"
                stroke="currentColor"
                strokeWidth={2}
              >
                <path strokeLinecap="round" strokeLinejoin="round" d="M4 4v5h.582m15.356 2A8.001 8.001 0 004.582 9m0 0H9m11 11v-5h-.581m0 0a8.003 8.003 0 01-15.357-2m15.357 2H15" />
              </svg>
            </button>
          </div>

          {/* Download Action Buttons */}
          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleDownloadCSV}
              disabled={csvGenerating || loading || !reportData}
              className="inline-flex items-center gap-2 px-3.5 py-2 rounded-xl border border-emerald-300 dark:border-emerald-700/60 bg-emerald-50 dark:bg-emerald-950/30 text-emerald-700 dark:text-emerald-300 hover:bg-emerald-100 dark:hover:bg-emerald-900/40 text-xs font-bold transition shadow-sm cursor-pointer disabled:opacity-50"
            >
              <svg className="w-4 h-4 text-emerald-600 dark:text-emerald-400" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M3 16.5v2.25A2.25 2.25 0 005.25 21h13.5A2.25 2.25 0 0021 18.75V16.5M16.5 12L12 16.5m0 0L7.5 12m4.5 4.5V3" />
              </svg>
              <span>{csvGenerating ? "Exporting CSV..." : "Download CSV"}</span>
            </button>

            <button
              type="button"
              onClick={handleDownloadPDF}
              disabled={pdfGenerating || loading || !reportData}
              className="inline-flex items-center gap-2 px-4 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-bold transition shadow-sm cursor-pointer disabled:opacity-50"
            >
              <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M19.5 14.25v-2.625a3.375 3.375 0 00-3.375-3.375h-1.5A1.125 1.125 0 0113.5 7.125v-1.5a3.375 3.375 0 00-3.375-3.375H8.25m.75 12 3 3m0 0 3-3m-3 3v-6m-1.5-9H5.625c-.621 0-1.125.504-1.125 1.125v17.25c0 .621.504 1.125 1.125 1.125h12.75c.621 0 1.125-.504 1.125-1.125V11.25a9 9 0 00-9-9z" />
              </svg>
              <span>{pdfGenerating ? "Generating PDF..." : "Download PDF Report"}</span>
            </button>
          </div>
        </div>

        {/* Scrollable Live Report Preview Content */}
        <div className="flex-1 overflow-y-auto space-y-4 pr-1">
          {error && (
            <div className="p-3 rounded-xl bg-rose-50 dark:bg-rose-950/30 border border-rose-200 dark:border-rose-900 text-rose-700 dark:text-rose-400 text-xs">
              {error}
            </div>
          )}

          {/* Workflow Summary Cards Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-5 gap-3">
            {/* Total Docs */}
            <div className="p-3.5 rounded-2xl bg-slate-50 dark:bg-slate-800/50 border border-slate-200 dark:border-slate-800">
              <span className="text-[10px] font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 block">
                Total Documents
              </span>
              <span className="text-xl font-black text-slate-900 dark:text-slate-100 mt-1 block">
                {summary.total}
              </span>
              <span className="text-[10px] text-slate-400 dark:text-slate-500">In period</span>
            </div>

            {/* In Transit */}
            <div className="p-3.5 rounded-2xl bg-amber-50 dark:bg-amber-950/20 border border-amber-200/80 dark:border-amber-900/30">
              <span className="text-[10px] font-bold uppercase tracking-wider text-amber-700 dark:text-amber-400 block">
                In Transit
              </span>
              <span className="text-xl font-black text-amber-600 dark:text-amber-400 mt-1 block">
                {summary.inTransit}
              </span>
              <span className="text-[10px] text-amber-600/70 dark:text-amber-400/60">Active routes</span>
            </div>

            {/* Pending Acceptance */}
            <div className="p-3.5 rounded-2xl bg-indigo-50 dark:bg-indigo-950/20 border border-indigo-200/80 dark:border-indigo-900/30">
              <span className="text-[10px] font-bold uppercase tracking-wider text-indigo-700 dark:text-indigo-400 block">
                Pending Accept
              </span>
              <span className="text-xl font-black text-indigo-600 dark:text-indigo-400 mt-1 block">
                {summary.pendingAcceptance}
              </span>
              <span className="text-[10px] text-indigo-600/70 dark:text-indigo-400/60">Awaiting user</span>
            </div>

            {/* Completed */}
            <div className="p-3.5 rounded-2xl bg-emerald-50 dark:bg-emerald-950/20 border border-emerald-200/80 dark:border-emerald-900/30">
              <span className="text-[10px] font-bold uppercase tracking-wider text-emerald-700 dark:text-emerald-400 block">
                Completed
              </span>
              <span className="text-xl font-black text-emerald-600 dark:text-emerald-400 mt-1 block">
                {summary.completed}
              </span>
              <span className="text-[10px] text-emerald-600/70 dark:text-emerald-400/60">Archived/done</span>
            </div>

            {/* Delayed / Overdue */}
            <div className="p-3.5 rounded-2xl bg-rose-50 dark:bg-rose-950/20 border border-rose-200/80 dark:border-rose-900/30 col-span-2 sm:col-span-1">
              <span className="text-[10px] font-bold uppercase tracking-wider text-rose-700 dark:text-rose-400 block">
                Delayed (&gt;48h)
              </span>
              <span className="text-xl font-black text-rose-600 dark:text-rose-400 mt-1 block">
                {summary.delayed}
              </span>
              <span className="text-[10px] text-rose-600/70 dark:text-rose-400/60">Needs attention</span>
            </div>
          </div>

          {/* User Activity & Top Handlers Banner */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
            {/* Account Activity Stats */}
            <div className="p-4 rounded-2xl bg-white dark:bg-slate-800/40 border border-slate-200 dark:border-slate-800 flex items-center justify-between">
              <div>
                <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400">
                  User &amp; Account Status
                </h4>
                <div className="flex items-center gap-4 mt-2">
                  <div>
                    <span className="text-lg font-black text-emerald-600 dark:text-emerald-400">
                      {userSummary.totalActive}
                    </span>
                    <span className="text-[11px] text-slate-500 dark:text-slate-400 block">Active</span>
                  </div>
                  <div className="h-7 w-px bg-slate-200 dark:bg-slate-700" />
                  <div>
                    <span className="text-lg font-black text-rose-600 dark:text-rose-400">
                      {userSummary.totalBlocked}
                    </span>
                    <span className="text-[11px] text-slate-500 dark:text-slate-400 block">Blocked</span>
                  </div>
                  <div className="h-7 w-px bg-slate-200 dark:bg-slate-700" />
                  <div>
                    <span className="text-lg font-black text-indigo-600 dark:text-indigo-400">
                      {userSummary.newUsersPeriod}
                    </span>
                    <span className="text-[11px] text-slate-500 dark:text-slate-400 block">New Registered</span>
                  </div>
                </div>
              </div>
            </div>

            {/* Top Active Handlers */}
            <div className="p-4 rounded-2xl bg-white dark:bg-slate-800/40 border border-slate-200 dark:border-slate-800">
              <h4 className="text-xs font-bold uppercase tracking-wider text-slate-500 dark:text-slate-400 mb-2">
                Top Active Handlers
              </h4>
              {userSummary.topHandlers?.length > 0 ? (
                <div className="flex flex-wrap gap-1.5">
                  {userSummary.topHandlers.map((h, i) => (
                    <span
                      key={h.name + i}
                      className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-xl bg-slate-100 dark:bg-slate-800 border border-slate-200 dark:border-slate-700 text-xs text-slate-800 dark:text-slate-200"
                    >
                      <span className="w-1.5 h-1.5 rounded-full bg-indigo-500" />
                      <span className="font-semibold">{h.name}</span>
                      <span className="text-[10px] font-bold text-indigo-600 dark:text-indigo-400">
                        {h.count} docs
                      </span>
                    </span>
                  ))}
                </div>
              ) : (
                <p className="text-xs text-slate-400">No active handler activity recorded for this period.</p>
              )}
            </div>
          </div>

          {/* Detailed Document Activity Log Preview */}
          <div className="bg-white dark:bg-slate-800/40 border border-slate-200 dark:border-slate-800 rounded-2xl overflow-hidden shadow-sm">
            <div className="p-4 border-b border-slate-200 dark:border-slate-800 flex flex-wrap items-center justify-between gap-3 bg-slate-50/70 dark:bg-slate-800/60">
              <div>
                <h3 className="text-sm font-bold text-slate-900 dark:text-white">
                  Document Activity Log Preview
                </h3>
                <p className="text-[11px] text-slate-500 dark:text-slate-400">
                  Showing {filteredDocuments.length} of {reportData?.documents?.length || 0} documents in this report
                </p>
              </div>

              {/* Table search & filter */}
              <div className="flex items-center gap-2">
                <input
                  type="text"
                  placeholder="Search tracking ID, title, user..."
                  value={searchDoc}
                  onChange={(e) => setSearchDoc(e.target.value)}
                  className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-3 py-1.5 text-xs text-slate-900 dark:text-slate-100 placeholder-slate-400 focus:outline-none focus:border-indigo-500 w-48 sm:w-56"
                />

                <select
                  value={statusFilter}
                  onChange={(e) => setStatusFilter(e.target.value)}
                  className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-700 rounded-xl px-2.5 py-1.5 text-xs text-slate-900 dark:text-slate-100 focus:outline-none cursor-pointer"
                >
                  <option value="ALL">All Statuses</option>
                  <option value="IN TRANSIT">In Transit</option>
                  <option value="PENDING ACCEPTANCE">Pending</option>
                  <option value="COMPLETED">Completed</option>
                </select>
              </div>
            </div>

            {/* Table */}
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs text-slate-700 dark:text-slate-300">
                <thead className="bg-slate-100/80 dark:bg-slate-800 text-slate-500 dark:text-slate-400 text-[10px] font-bold uppercase tracking-wider">
                  <tr>
                    <th className="py-2.5 px-3">Tracking ID</th>
                    <th className="py-2.5 px-3">Document Title</th>
                    <th className="py-2.5 px-3">Priority</th>
                    <th className="py-2.5 px-3">Current Holder</th>
                    <th className="py-2.5 px-3">Status</th>
                    <th className="py-2.5 px-3">SLA Due Date</th>
                    <th className="py-2.5 px-3">Last Updated</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
                  {loading ? (
                    <tr>
                      <td colSpan="7" className="py-8 text-center text-slate-400">
                        <span className="inline-block animate-spin mr-2">⟳</span> Loading report data...
                      </td>
                    </tr>
                  ) : filteredDocuments.length === 0 ? (
                    <tr>
                      <td colSpan="7" className="py-8 text-center text-slate-400">
                        No documents found matching the selected timeframe and filter.
                      </td>
                    </tr>
                  ) : (
                    filteredDocuments.map((doc) => (
                      <tr
                        key={doc._id}
                        className="hover:bg-slate-50/80 dark:hover:bg-slate-800/50 transition-colors"
                      >
                        <td className="py-2.5 px-3 font-mono font-bold text-indigo-600 dark:text-indigo-400 whitespace-nowrap">
                          <button
                            type="button"
                            onClick={() => handleCopyId(doc.trackingId)}
                            className="inline-flex items-center gap-1 hover:underline cursor-pointer"
                            title="Click to copy tracking ID"
                          >
                            <span>{doc.trackingId}</span>
                            {copiedId === doc.trackingId ? (
                              <span className="text-[10px] text-emerald-500 font-sans">Copied!</span>
                            ) : (
                              <svg className="w-3 h-3 text-slate-400" fill="none" viewBox="0 0 24 24" stroke="currentColor">
                                <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M8 16H6a2 2 0 01-2-2V6a2 2 0 012-2h8a2 2 0 012 2v2m-6 12h8a2 2 0 002-2v-8a2 2 0 00-2-2h-8a2 2 0 00-2 2v8a2 2 0 002 2z" />
                              </svg>
                            )}
                          </button>
                        </td>
                        <td className="py-2.5 px-3 font-medium text-slate-900 dark:text-slate-100 max-w-xs truncate">
                          {doc.title}
                        </td>
                        <td className="py-2.5 px-3 whitespace-nowrap">
                          <PriorityBadge priority={doc.priority} showNormal={true} />
                        </td>
                        <td className="py-2.5 px-3 text-slate-600 dark:text-slate-300 whitespace-nowrap">
                          {doc.currentHolder}
                        </td>
                        <td className="py-2.5 px-3 whitespace-nowrap">
                          <span
                            className={`inline-flex items-center px-2 py-0.5 rounded-full text-[10px] font-bold ${
                              doc.status === "Completed"
                                ? "bg-emerald-100 dark:bg-emerald-950/40 text-emerald-700 dark:text-emerald-300 border border-emerald-300 dark:border-emerald-800"
                                : doc.status === "In Transit"
                                ? "bg-amber-100 dark:bg-amber-950/40 text-amber-700 dark:text-amber-300 border border-amber-300 dark:border-amber-800"
                                : "bg-indigo-100 dark:bg-indigo-950/40 text-indigo-700 dark:text-indigo-300 border border-indigo-300 dark:border-indigo-800"
                            }`}
                          >
                            {doc.status}
                          </span>
                        </td>
                        <td className="py-2.5 px-3 whitespace-nowrap">
                          <DueDateBadge
                            dueDate={doc.dueDate}
                            isOverdue={doc.isOverdue}
                            isCompleted={doc.status === "Completed"}
                          />
                          {!doc.dueDate && <span className="text-slate-400 text-[10px]">None</span>}
                        </td>
                        <td className="py-2.5 px-3 text-[11px] text-slate-400 dark:text-slate-500 whitespace-nowrap">
                          {formatDate(doc.updatedAt || doc.createdAt)}
                        </td>
                      </tr>
                    ))
                  )}
                </tbody>
              </table>
            </div>
          </div>
        </div>

        {/* Modal Footer */}
        <div className="flex items-center justify-between pt-3 mt-3 border-t border-slate-200 dark:border-slate-800 flex-shrink-0">
          <p className="text-xs text-slate-500 dark:text-slate-400">
            {reportData?.documents?.length || 0} total records • Ready for export in PDF or CSV format
          </p>
          <button
            onClick={onClose}
            className="px-6 py-2 bg-slate-200 hover:bg-slate-300 dark:bg-slate-800 dark:hover:bg-slate-700 text-slate-800 dark:text-slate-200 font-semibold text-xs sm:text-sm rounded-xl transition-colors shadow-sm cursor-pointer"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
}
